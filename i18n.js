export const dict = { en, hi, bho };
export const LANGS = ['en', 'hi', 'bho'];

const STORAGE_KEY = 'srisai-lang';
let current = 'en';

const hasDoc = () => typeof document !== 'undefined';
const storage = () => {
  try { return typeof localStorage !== 'undefined' ? localStorage : null; } catch { return null; }
};

export function getLang() {
  return current;
}

// t(key, vars) — dict[lang][key] ?? dict.en[key] ?? key, with {name} interpolation.
export function t(key, vars = {}) {
  const raw = dict[current]?.[key] ?? dict.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function applyTranslations(root) {
  if (!hasDoc()) return;
  const scope = root ?? document;
  const vars = (el) => {
    const raw = el.getAttribute('data-i18n-vars');
    if (!raw) return {};
    try { return JSON.parse(raw); } catch { return {}; }
  };
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'), vars(el));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'), vars(el));
  });
  scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'), vars(el)));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'), vars(el));
  });
}

export function setLang(code) {
  if (!LANGS.includes(code)) return current;
  current = code;
  const s = storage();
  if (s) { try { s.setItem(STORAGE_KEY, code); } catch { /* quota / private mode */ } }
  if (hasDoc()) {
    document.documentElement.lang = code;
    applyTranslations();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: code } }));
  }
  return current;
}

export function initLang() {
  let code = null;
  const s = storage();
  if (s) { try { code = s.getItem(STORAGE_KEY); } catch { code = null; } }
  if (!LANGS.includes(code)) {
    const nav = typeof navigator !== 'undefined' ? navigator.language || '' : '';
    code = nav.startsWith('hi') ? 'hi' : 'en';
  }
  current = code;
  if (hasDoc()) {
    document.documentElement.lang = code;
    applyTranslations();
  }
  return current;
}

export function onLangChange(fn) {
  if (hasDoc()) document.addEventListener('langchange', fn);
}
